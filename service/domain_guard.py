# -*- coding: utf-8 -*-
# service/domain_guard.py
# 域守卫 —— 判断问题是不是"本公司 IT 运维"范围内的, 分两段做
#
# 【第一段: 寒暄黑名单】check()
#   闲聊问题原本要完整走一遍 错误码 -> FAQ -> RAG(双向量+重排), (20,8) 配置下
#   这条链路约 14.5 秒, 最后靠 top_score < 0.1 才被拦住。拒答和回答一样贵。
#   更糟的是每句"你好""谢谢"都以 rag_low 落进 knowledge_gaps, 把真正的知识盲区
#   稀释掉, 运营看到的 Top N 一半是噪声。
#   这一段的判据是黑名单: 闲聊有固定模式, 可以穷举。
#   触发条件必须同时满足:
#     1. 整句被某条正则 ^...$ 完全匹配 —— 所以"你好, 我电脑蓝屏了"不会被拦
#     2. 去掉尾标点后长度 <= MAX_LEN —— 兜一层, 防止长句恰好整句匹配
#
# 【第二段: 域外判定】is_out_of_domain()
#   拦住"不是寒暄、但也不是 IT 问题"的越界题(帮我写首诗 / 今天股票涨了吗)。
#   做法是 IT 术语快路径 + LLM 二分类兜底, 详见文件下半部分的说明。
#
# 两段的共同原则: 宁可漏放, 不可误杀。
#   漏放的问题仍会被 0.1 分数阈值拦住, 行为与改动前一致;
#   误杀一个真需求, 用户会直接得到"这不归我管", 严重一个量级。
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from base.config import config
from base.logger import logger

MAX_LEN = 12
_SERVICE_LINE = getattr(config, "CUSTOMER_SERVICE", "IT 服务台")

_PATTERNS = [
    # 问候
    r"^(你好|您好|hi|hello|hey|在吗|在么|在不在|早|早上好|上午好|中午好|下午好|晚上好|哈喽|嗨)$",
    # 感谢
    r"^(谢谢|多谢|感谢|谢了|thanks|thank you|thx|3q)$",
    # 告别
    r"^(再见|拜拜|bye|晚安|先这样)$",
    # 问身份 / 问能力
    r"^(你是谁|你叫什么|你叫什么名字|你是机器人吗|你是什么模型|谁开发的你|你能干什么|你会什么)$",
    # 时间天气
    r"^(今天|明天|昨天)?(天气|下雨|气温|几号|星期几|周几)(怎么样|如何|多少)?$",
    # 闲聊
    r"^(讲个笑话|唱首歌|陪我聊|陪我聊天|好无聊|无聊|你吃饭了吗|吃了吗)$",
    # 吃喝玩乐(兜住"今晚吃什么"这类)
    r"^(今天|明天|今晚|晚上|中午)?(晚上|中午|早上)?(吃|喝)(什么|啥|点什么)(好|呢)?$",
    # 应答语气词
    r"^(好的|好|嗯|嗯嗯|哦|ok|okay|收到|明白了)$",
]
_COMPILED = [re.compile(p, re.IGNORECASE) for p in _PATTERNS]

# 感谢类单独给收尾话术, 其余给引导语
_THANKS = re.compile(r"谢谢|多谢|感谢|谢了|thanks|thank you|thx|3q", re.IGNORECASE)

# 尾部标点/语气符号, 匹配前先剥掉("你好!" 应该等同 "你好")
_TRAILING = re.compile(r"[\s!！。.~～?？,，、]+$")


def check(query):
    """
    判断是否应该在进三层路由之前短路。
    :param query: 用户原始问题
    :return: (hit: bool, reply: str)  hit=True 表示命中闲聊, 直接回 reply, 不进三层
    """
    q = (query or "").strip()
    if not q:
        return False, ""
    core = _TRAILING.sub("", q)
    if not core or len(core) > MAX_LEN:
        return False, ""
    for pat in _COMPILED:
        if pat.match(core):
            return True, _build_reply(core)
    return False, ""


def _build_reply(core):
    if _THANKS.search(core):
        return "不客气，还有其他 IT 问题随时问我。"
    # 闲聊给"引导", 域外给"婉拒" —— 两种语气不能混:
    # 对"你好"说"这个问题不在我的服务范围内"是赶客。
    return (
        "我是 IT 运维知识库助手，只能回答公司内部 IT 相关问题，"
        "比如账号权限、网络连接、软件报错、打印机、VPN 等。\n"
        "遇到故障可以直接描述现象，比如「电脑蓝屏了怎么办」。"
    )


# ============================================================
# 第二部分: 域外判定(闲聊黑名单之外的"不是 IT 问题"的问题)
# ============================================================
# 为什么黑名单不够:
#   "帮我写一首关于秋天的诗" 不含任何寒暄特征, 上面那堆正则穷举不到。
#   越界话题是开放集合(写诗/翻译/算数/问股票/问天气/问法律...), 永远列不全。
#   但"IT 域内"的词汇是相对封闭的, 可以列。所以改用反向思路: 命中 IT 术语 -> 放行。
#
# 为什么也不能只靠 reranker 分数:
#   实测同域错配 0.5382 > 正确答案 0.2394。分数衡量的是"query 和文档字面像不像",
#   不是"这个问题属不属于本领域"。调高阈值只会把长尾真需求一起误杀(T1-T5 已验证:
#   阈值为 0.1 时, 越界题 0.0001~0.0003, 但长尾同域题也可能是 0.2 量级)。
#
# 于是分两段, 把成本压在真正需要的地方:
#   术语命中            -> 直接放行, 零成本
#   术语不命中 + 即将进 RAG -> 付一次轻量 LLM 二分类(约 300~800ms)
#   只有"错误码和 FAQ 都没命中、马上就要烧 14.5 秒重排"的问题才会走到第二段。
#
# 核心原则仍然是"宁可漏放, 不可误杀": LLM 判定失败/超时/输出无法解析, 一律放行。

