def has_it_term(query):
    """是否含 IT 领域术语(快路径, 零成本)。命中即认为域内, 不再调 LLM。"""
    ql = (query or "").lower()
    if not ql:
        return False
    return any(t in ql for t in _IT_TERMS_LOWER)


def is_out_of_domain(query, llm=None):
    """
    判定一个问题是否属于"域外"(不该走 RAG, 也不该进知识盲区表)。

    判定顺序:
      1. 含 IT 术语 -> 域内, 直接放行(零成本, 覆盖大部分真实问题)
      2. 不含术语 -> 调一次轻量 LLM 二分类(约 300~800ms)
      3. 调用失败/超时/输出无法解析 -> 放行(宁可漏放, 不可误杀)

    调用时机很关键: 放在"错误码层和 FAQ 层都没命中、即将进入 RAG"的位置,
    这样域内问题永远不付这次判定的成本, 只有可能被拒答的问题才付。

    :param query: 用户问题
    :param llm: 可复用已有的 LLMClient(省一次对象创建), None 则内部创建
    :return: (out_of_domain: bool, via: str)   via 取值: term / llm / pass / empty
    """
    q = (query or "").strip()
    if not q:
        return False, "empty"
    if has_it_term(q):
        return False, "term"
    try:
        if llm is None:
            from service.llm_client import LLMClient
            llm = LLMClient(model=config.LLM_FLASH_MODEL)
        ans = (llm.generate(_DOMAIN_SYSTEM, f"用户问题：{q}", temperature=0.0) or "").upper()
        ans = ans.replace(" ", "").replace("_", "")
        # 只认显式的 NOT_IT; 其余(含 IT、空串、乱输出)一律放行
        return ("NOTIT" in ans), "llm"
    except Exception as e:
        logger.warning(f"[域判定] LLM 调用失败, 按域内放行: {e}")
        return False, "pass"


